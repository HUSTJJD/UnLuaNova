$ErrorActionPreference = 'Stop'
$Tools = Split-Path -Parent $PSScriptRoot
$RepoRoot = Split-Path -Parent $Tools
$PowerShellExe = (Get-Process -Id $PID).Path
. (Join-Path $Tools 'ReleaseSupport.ps1')
. (Join-Path $Tools 'ReleaseCache.ps1')
. (Join-Path $Tools 'TypeCheckSupport.ps1')
$Temporary = Join-Path ([IO.Path]::GetTempPath()) ('UnLuaNova-release-test-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $Temporary | Out-Null
function Assert([bool] $Condition, [string] $Message) { if (-not $Condition) { throw $Message } }
try {
    Assert ((Get-TypeCheckExitCode 0 0 0) -eq 0) 'Clean type check failed'
    Assert ((Get-TypeCheckExitCode 1 0 7) -eq 0) 'Warnings contradicted the nonblocking diagnostic policy'
    Assert ((Get-TypeCheckExitCode 1 1 7) -ne 0) 'Type error was accepted'
    Assert ((Get-TypeCheckExitCode 0 1 0) -ne 0) 'Analyzer zero exit hid a type error'
    Assert ((Get-TypeCheckExitCode 1 0 0) -ne 0) 'Unexplained analyzer failure was accepted'
    Assert ((Get-TypeCheckExitCode 7 0 7) -eq 7) 'Abnormal analyzer exit was hidden by warnings'
    Assert ((Get-TypeCheckExitCode 0 0 0 $false) -ne 0) 'Missing analysis result was accepted'
    foreach ($File in @(Get-ChildItem -LiteralPath $Tools -Filter '*.ps1' -File) + @(Get-ChildItem -LiteralPath $PSScriptRoot -Filter '*.ps1' -File)) {
        $Tokens = $null
        $ParseErrors = $null
        [Management.Automation.Language.Parser]::ParseFile($File.FullName, [ref]$Tokens, [ref]$ParseErrors) | Out-Null
        Assert (-not $ParseErrors) "Invalid PowerShell syntax: $($File.FullName)"
    }
    $Ini = Join-Path $Temporary 'config.ini'
    [IO.File]::WriteAllText($Ini, "[Other]`r`nValue=keep`r`n[Target]`r`nKey=old`r`nKey=duplicate`r`n")
    Set-ReleaseIniValue $Ini '[Target]' 'Key' 'new'
    Set-ReleaseIniValue $Ini '[New]' 'Enabled' 'True'
    $Text = [IO.File]::ReadAllText($Ini)
    Assert ($Text.Contains('Value=keep') -and $Text.Contains('Enabled=True')) 'INI lost unrelated content'
    Assert (([regex]::Matches($Text, 'Key=')).Count -eq 1 -and $Text.Contains('Key=new')) 'INI key not replaced exactly once'

    $Project = Join-Path $Temporary 'demo project/Demo.uproject'
    # The generator owns <UnLuaNova>/Source/UnLuaNova/Generated/Backends/<Backend>/.
    $GeneratedRoot = Join-Path (Split-Path -Parent $Project) 'Plugins/UnLuaNova/Source/UnLuaNova/Generated/Backends'
    $LuaDir = Join-Path $GeneratedRoot 'Lua'
    $LuauDir = Join-Path $GeneratedRoot 'Luau'
    New-Item -ItemType Directory -Path $LuaDir, $LuauDir -Force | Out-Null
    $LuaSource = Join-Path $LuaDir 'UnLuaNovaStaticBinding_Generated.cpp'
    $LuauSource = Join-Path $LuauDir 'UnLuaNovaStaticBinding_Generated.cpp'
    Assert ((Get-ReleaseStaticBindingSource $Project 'Lua') -eq $LuaSource) 'Lua binding layout was not resolved'
    Assert ((Get-ReleaseStaticBindingSource $Project 'Luau') -eq $LuauSource) 'Luau binding layout was not resolved'
    Assert ($LuaSource -ne $LuauSource) 'The two backends still share one generated source'
    $Rejected = $false
    try { Get-ReleaseStaticBindingSource $Project 'Other' | Out-Null } catch { $Rejected = $true }
    Assert $Rejected 'An unknown backend was accepted as a binding directory'

    # The gate must reject a missing file, a file the generator does not own, a file from
    # the other backend, and a file with a guard that disagrees with its backend label.
    Assert (-not (Test-ReleaseBindingGenerated -Path $LuaSource -Backend 'Lua')) 'Missing bindings passed the gate'
    [IO.File]::WriteAllText($LuaSource, '// not generated')
    Assert (-not (Test-ReleaseBindingGenerated -Path $LuaSource -Backend 'Lua')) 'Unrecognized source passed the gate'
    $Header = '// Generated by UnLuaNovaStaticBindingGenerator. Do not edit.'
    $LuaBody = @($Header, '// fingerprint: v2-1-ABCDEF', '// backend: Lua', '',
        '#if defined(UNLUANOVA_LUA_BACKEND) && UNLUANOVA_LUA_BACKEND == 0',
        'static FStaticTypeBinding TypeBinding_Foo;', '#endif') -join "`n"
    [IO.File]::WriteAllText($LuaSource, $LuaBody)
    Assert (Test-ReleaseBindingGenerated -Path $LuaSource -Backend 'Lua') 'Valid Lua bindings were rejected'
    Assert (-not (Test-ReleaseBindingGenerated -Path $LuaSource -Backend 'Luau')) 'Lua bindings passed the Luau gate'
    $WrongGuard = $LuaBody.Replace('UNLUANOVA_LUA_BACKEND == 0', 'UNLUANOVA_LUA_BACKEND == 1')
    [IO.File]::WriteAllText($LuaSource, $WrongGuard)
    Assert (-not (Test-ReleaseBindingGenerated -Path $LuaSource -Backend 'Lua')) 'A mismatched backend guard passed the gate'
    $LuauBody = $LuaBody.Replace('// backend: Lua', '// backend: Luau').Replace('UNLUANOVA_LUA_BACKEND == 0', 'UNLUANOVA_LUA_BACKEND == 1')
    [IO.File]::WriteAllText($LuauSource, $LuauBody)
    Assert (Test-ReleaseBindingGenerated -Path $LuauSource -Backend 'Luau') 'Valid Luau bindings were rejected'
    Assert ([IO.File]::ReadAllText($LuaSource) -eq $WrongGuard) 'Checking one backend modified the other one'

    # A tree without the plugin directory still resolves the project-local backend path.
    $LegacyProject = Join-Path $Temporary 'legacy/Demo.uproject'
    $LegacyDir = Join-Path $Temporary 'legacy/Source/Demo/Generated/Backends/Lua'
    New-Item -ItemType Directory -Path $LegacyDir -Force | Out-Null
    $LegacySource = Join-Path $LegacyDir 'UnLuaNovaStaticBinding_Generated.cpp'
    Assert ((Get-ReleaseStaticBindingSource $LegacyProject 'Lua') -eq $LegacySource) 'Legacy binding layout was not resolved'

    # Only the cooked game's missing HTML template is an allowed UE automation error.
    $CleanLog = Join-Path $Temporary 'automation-clean.log'
    [IO.File]::WriteAllText($CleanLog, "[0]LogAutomationController: Display: Loading results html template...`n[0]LogAutomationController: Error: Failed to load test report html template - No report will be generated.`n")
    Assert-ReleaseAutomationLog $CleanLog
    $BadLog = Join-Path $Temporary 'automation-bad.log'
    [IO.File]::WriteAllText($BadLog, "[0]LogAutomationController: Error: something else broke`n")
    $Rejected = $false
    try { Assert-ReleaseAutomationLog $BadLog } catch { $Rejected = $_.Exception.Message -like 'Unexpected UE automation error*' }
    Assert $Rejected 'An unexpected UE automation error was accepted'

    # Real child process, no compiler or UE. Verify quoting and nonzero exit propagation.
    $Arguments = @('space path\', 'embedded"quote', '', '-value=two words', 'literal $() and `backticks`')
    $Probe = Join-Path $PSScriptRoot 'fixtures/argv_probe.py'
    $Log = Join-Path $Temporary 'argv.log'
    Invoke-ReleaseProcess -File (Get-Command python).Source -Arguments (@($Probe) + $Arguments) -Log $Log -WorkingDirectory $Temporary
    $Actual = Get-Content $Log -Raw | ConvertFrom-Json
    Assert ($Actual.Count -eq $Arguments.Count) 'Argument count changed'
    for ($Index = 0; $Index -lt $Arguments.Count; $Index++) {
        Assert ($Actual[$Index] -ceq $Arguments[$Index]) "Argument $Index changed"
    }
    $Failed = $false
    try {
        Invoke-ReleaseProcess -File $PowerShellExe -Arguments @('-NoProfile', '-NonInteractive', '-Command', 'exit 7') `
            -Log (Join-Path $Temporary 'failure.log') -WorkingDirectory $Temporary
    } catch { $Failed = $_.Exception.Message -like 'Exit 7:*' }
    Assert $Failed 'Nonzero process exit did not fail the gate'
    $Failed = $false
    try {
        Invoke-ReleaseProcess -File $PowerShellExe -Arguments @('-NoProfile', '-NonInteractive', '-Command', 'Start-Sleep -Seconds 15') `
            -Log (Join-Path $Temporary 'timeout.log') -WorkingDirectory $Temporary -Minutes 0.01
    } catch { $Failed = $_.Exception.Message -like 'Timeout*' }
    Assert $Failed 'Process timeout did not fail the gate'
    Assert ($script:ReleaseChildProcesses.Count -eq 0) 'A finished external process stayed registered'

    # A cancelled release must not leave its build process holding UBT's mutex.
    $Orphan = Start-Process -FilePath $PowerShellExe -ArgumentList '-NoProfile -NonInteractive -Command Start-Sleep -Seconds 60' -PassThru
    $script:ReleaseChildProcesses[$Orphan.Id] = $Orphan.StartTime
    Stop-ReleaseChildProcesses
    Assert (-not (Get-Process -Id $Orphan.Id -ErrorAction SilentlyContinue)) 'Cancellation left a child process alive'
    Assert ($script:ReleaseChildProcesses.Count -eq 0) 'Child process registry was not cleared'

    # Build reuse. A fingerprint has to move when its inputs move, and a hit has to become a
    # miss the moment the recorded artifact is replaced - reusing another backend's build, or
    # a build that was deleted, is the whole thing this has to prevent.
    Initialize-ReleaseCache -Directory (Join-Path $Temporary 'release-cache')
    $TreeDir = Join-Path $Temporary 'tree/src'
    New-Item -ItemType Directory -Path (Join-Path $TreeDir 'Generated') -Force | Out-Null
    [IO.File]::WriteAllText((Join-Path $TreeDir 'A.cpp'), 'int a;')
    [IO.File]::WriteAllText((Join-Path $TreeDir 'Generated/Bindings.cpp'), 'int generated;')
    $Before = Get-ReleaseTreeFingerprint -Roots @($TreeDir)
    Assert ($Before -match '^[0-9a-f]{64}$') 'Tree fingerprint was empty'
    Assert ($Before -eq (Get-ReleaseTreeFingerprint -Roots @($TreeDir))) 'Fingerprint is not stable across calls'
    [IO.File]::WriteAllText((Join-Path $TreeDir 'Generated/Bindings.cpp'), 'int regenerated;')
    Assert ($Before -eq (Get-ReleaseTreeFingerprint -Roots @($TreeDir))) 'Generated output changed the fingerprint of its own producer'
    [IO.File]::WriteAllText((Join-Path $TreeDir 'A.cpp'), 'int b;')
    $After = Get-ReleaseTreeFingerprint -Roots @($TreeDir)
    Assert ($Before -ne $After) 'A source change did not change the fingerprint'
    Assert ((Get-ReleaseTreeFingerprint -Roots @($TreeDir) -MetadataOnly) -ne $After) 'Metadata mode ignored file contents'

    $Artifact = Join-Path $Temporary 'build/out.dll'
    New-Item -ItemType Directory -Path (Split-Path -Parent $Artifact) -Force | Out-Null
    [IO.File]::WriteAllText($Artifact, 'binary')
    Assert (-not (Test-ReleaseCacheHit -Key 'stage' -Fingerprint $Before -Paths @($Artifact))) 'An unknown stage was reused'
    Set-ReleaseCacheEntry -Key 'stage' -Fingerprint $Before -Paths @($Artifact)
    Assert (Test-ReleaseCacheHit -Key 'stage' -Fingerprint $Before -Paths @($Artifact)) 'Unchanged inputs were not reused'
    Assert (-not (Test-ReleaseCacheHit -Key 'stage' -Fingerprint $After -Paths @($Artifact))) 'Changed inputs reused an older build'
    # The index has to survive being written and read back: that is what happens between two
    # runs, and a load that quietly drops the file turns every stage into a full rebuild.
    Set-ReleaseCacheEntry -Key 'roundtrip' -Fingerprint $Before -Paths @($Artifact)
    Initialize-ReleaseCache -Directory (Join-Path $Temporary 'release-cache')
    Assert (Test-ReleaseCacheHit -Key 'roundtrip' -Fingerprint $Before -Paths @($Artifact)) 'A cache entry did not survive being read back from disk'

    # A stage that starts tracking another file still hits while that file is there, and
    # misses as soon as it is not.
    Assert (Test-ReleaseCacheHit -Key 'stage' -Fingerprint $Before -Paths @($Artifact, $Artifact)) 'An existing extra artifact broke reuse'
    Assert (-not (Test-ReleaseCacheHit -Key 'stage' -Fingerprint $Before -Paths @($Artifact, (Join-Path $Temporary 'build/absent.dll')))) 'A missing newly tracked artifact was reused'
    [IO.File]::WriteAllText($Artifact, 'rebuilt by the other backend')
    Assert (-not (Test-ReleaseCacheHit -Key 'stage' -Fingerprint $Before -Paths @($Artifact))) 'A replaced artifact was reused'
    # A stage whose output is missing must not be recorded: "built" with no binary would let
    # the next run skip the build and then have nothing to test.
    Set-ReleaseCacheEntry -Key 'missing' -Fingerprint $Before -Paths @((Join-Path $Temporary 'build/absent.dll'))
    Assert (-not (Test-ReleaseCacheHit -Key 'missing' -Fingerprint $Before -Paths @())) 'A missing artifact was recorded as a build'

    # A type check summary lives in the run directory, so a hit has to put it back: the
    # evidence gate reads that file, and "no file" is a failed gate rather than a skip.
    $Summary = Join-Path $Temporary 'run/lua-analyze.json'
    New-Item -ItemType Directory -Path (Split-Path -Parent $Summary) -Force | Out-Null
    [IO.File]::WriteAllText($Summary, '{"errors":0}')
    Save-ReleaseCacheFile -Key 'Lua-typecheck' -Source $Summary
    Remove-Item -LiteralPath $Summary -Force
    Assert (Restore-ReleaseCacheFile -Key 'Lua-typecheck' -Destination $Summary) 'A cached summary was not restored'
    Assert ((Get-Content -LiteralPath $Summary -Raw) -eq '{"errors":0}') 'The restored summary changed'

    # Which backend the tree holds has to come from what UBT compiled, not from the ini.
    $HeaderRoot = Join-Path $Temporary 'plugin'
    $HeaderDir = Join-Path $HeaderRoot 'Intermediate/Build/Win64/x64/UnrealEditor/Development/UnLuaNova'
    New-Item -ItemType Directory -Path $HeaderDir -Force | Out-Null
    Assert (-not (Get-ReleaseBuiltBackend $HeaderRoot)) 'An unbuilt tree reported a backend'
    [IO.File]::WriteAllText((Join-Path $HeaderDir 'Definitions.UnLuaNova.h'), '#define UNLUANOVA_LUA_BACKEND 1')
    Assert ((Get-ReleaseBuiltBackend $HeaderRoot) -eq 'Luau') 'A Luau build was not recognized'
    [IO.File]::WriteAllText((Join-Path $HeaderDir 'Definitions.UnLuaNova.h'), '#define UNLUANOVA_LUA_BACKEND 0')
    Assert ((Get-ReleaseBuiltBackend $HeaderRoot) -eq 'Lua') 'A Lua build was not recognized'
    Assert (-not (Resolve-ReleaseGameExe (Join-Path $Temporary 'absent-stage') 'Demo' 'Development')) 'A missing package resolved'

    # -NoCache has to mean no reuse at all.
    Initialize-ReleaseCache -Directory (Join-Path $Temporary 'release-cache') -Disabled
    Assert (-not (Test-ReleaseCacheHit -Key 'stage' -Fingerprint $Before -Paths @($Artifact))) 'A disabled cache reported a hit'

    # Packaged Server and Game peers have different executable paths.
    $PeerRoot = Join-Path $Temporary 'peers'
    New-Item -ItemType Directory -Path $PeerRoot | Out-Null
    $PeerStarted = [datetime]::UtcNow.AddSeconds(-1)
    $PythonRuntime = (& python -c 'import sys; print(sys.executable)').Trim()
    $PeerProcess = Start-Process -FilePath $PythonRuntime -ArgumentList @('-c', '"import time; time.sleep(30)"') -WindowStyle Hidden -PassThru
    try {
        # A freshly started process can briefly expose an empty Path. Writing that into the
        # topology makes Stop-ReleasePeers skip the peer, so the assertion below flakes.
        $PeerPath = ''
        for ($Attempt = 0; $Attempt -lt 50 -and -not $PeerPath; $Attempt++) {
            Start-Sleep -Milliseconds 100
            $PeerPath = (Get-Process -Id $PeerProcess.Id -ErrorAction SilentlyContinue).Path
        }
        Assert (-not [string]::IsNullOrEmpty($PeerPath)) 'Peer process exposed no executable path'
        @{ exe = $PowerShellExe; peers = @(@{ pid = $PeerProcess.Id; exe = $PowerShellExe }) } |
            ConvertTo-Json -Depth 4 | Set-Content (Join-Path $PeerRoot 'topology.json')
        Stop-ReleasePeers $PeerRoot $PeerStarted
        $PeerProcess.Refresh()
        Assert (-not $PeerProcess.HasExited) 'Cleanup terminated a mismatched executable'
        @{ exe = $PowerShellExe; peers = @(@{ pid = $PeerProcess.Id; exe = $PeerPath }) } |
            ConvertTo-Json -Depth 4 | Set-Content (Join-Path $PeerRoot 'topology.json')
        Stop-ReleasePeers $PeerRoot $PeerStarted
        Assert ($PeerProcess.WaitForExit(5000)) 'Cleanup ignored the per-peer executable'
    } finally {
        if (-not $PeerProcess.HasExited) { $PeerProcess.Kill() }
        $PeerProcess.Dispose()
    }

    $Before = Get-FileHash (Join-Path $RepoRoot 'Config/DefaultUnLuaNova.ini')
    # RunTests.ps1 takes no parameters; DryRun is a maintainer switch on the pipeline it
    # forwards to, not something a release caller can pass.
    Invoke-ReleaseProcess -File $PowerShellExe -Arguments @('-NoProfile', '-NonInteractive', '-File',
        (Join-Path $Tools 'ReleasePipeline.ps1'), '-DryRun') -Log (Join-Path $Temporary 'dry-run.log') -WorkingDirectory $RepoRoot
    Assert ((Get-FileHash $Before.Path).Hash -eq $Before.Hash) 'DryRun modified project config'
    $Failed = $false
    try {
        Invoke-ReleaseProcess -File $PowerShellExe -Arguments @('-NoProfile', '-NonInteractive', '-File',
            (Join-Path $Tools 'RunTests.ps1'), '-SkipBuild') -Log (Join-Path $Temporary 'partial.log') -WorkingDirectory $RepoRoot
    } catch { $Failed = $true }
    Assert $Failed 'Parameterless entry point accepted a switch'
    $Failed = $false
    $FailedOutput = Join-Path $Temporary 'preflight-report'
    try {
        Invoke-ReleaseProcess -File $PowerShellExe -Arguments @('-NoProfile', '-NonInteractive', '-File',
            (Join-Path $Tools 'ReleasePipeline.ps1'), '-EnginePath', (Join-Path $Temporary 'missing-engine'),
            '-OutputDir', $FailedOutput) -Log (Join-Path $Temporary 'preflight.log') -WorkingDirectory $RepoRoot
    } catch { $Failed = $true }
    Assert $Failed 'Missing engine was accepted'
    $Summary = Get-Content (Join-Path $FailedOutput 'release-summary.json') -Raw | ConvertFrom-Json
    Assert ($Summary.complete -and -not $Summary.passed) 'Failed preflight lost the aggregate verdict'
    # The stage list grows whenever a check is added to the Release. Assert by name
    # against the pipeline's own required-stage list rather than a hard-coded count:
    # every stage that never ran must still be present in the summary.
    $Required = @($Summary.required_stages)
    $Seen = @($Summary.stages | ForEach-Object { $_.name })
    $Absent = @($Required | Where-Object { $Seen -notcontains $_ })
    Assert ($Required.Count -gt 0 -and $Absent.Count -eq 0) `
        ('Unexecuted stages disappeared from summary: ' + ($Absent -join ', '))
    Assert ((Get-FileHash $Before.Path).Hash -eq $Before.Hash) 'Failed preflight modified project config'
    Write-Host 'Release support tests passed.'
} finally {
    $Resolved = [IO.Path]::GetFullPath($Temporary)
    $ExpectedParent = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\') + '\'
    if ($Resolved.StartsWith($ExpectedParent, [StringComparison]::OrdinalIgnoreCase) -and
        [IO.Path]::GetFileName($Resolved).StartsWith('UnLuaNova-release-test-')) {
        Remove-Item -LiteralPath $Resolved -Recurse -Force
    }
}
