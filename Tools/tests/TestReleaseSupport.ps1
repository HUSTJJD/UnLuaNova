$ErrorActionPreference = 'Stop'
$Tools = Split-Path -Parent $PSScriptRoot
$RepoRoot = Split-Path -Parent $Tools
$PowerShellExe = (Get-Process -Id $PID).Path
. (Join-Path $Tools 'ReleaseSupport.ps1')
. (Join-Path $Tools 'TypeCheckSupport.ps1')
$Temporary = Join-Path ([IO.Path]::GetTempPath()) ('UnLuaNova-release-test-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $Temporary | Out-Null
function Assert([bool] $Condition, [string] $Message) { if (-not $Condition) { throw $Message } }
try {
    Assert ((Get-TypeCheckExitCode 0 0 0) -eq 0) 'Clean type check failed'
    Assert ((Get-TypeCheckExitCode 1 0 7) -eq 0) 'Warnings contradicted the nonblocking diagnostic policy'
    Assert ((Get-TypeCheckExitCode 1 1 7) -ne 0) 'Type error was accepted'
    Assert ((Get-TypeCheckExitCode 0 1 0) -ne 0) 'Analyzer zero exit hid a type error'
    Assert ((Get-TypeCheckExitCode 1 0 0) -ne 0) 'Unexplained analyzer failure was accepted'
    Assert ((Get-TypeCheckExitCode 7 0 7) -eq 7) 'Abnormal analyzer exit was hidden by warnings'
    Assert ((Get-TypeCheckExitCode 0 0 0 $false) -ne 0) 'Missing analysis result was accepted'
    foreach ($File in @(Get-ChildItem -LiteralPath $Tools -Filter '*.ps1' -File) + @(Get-ChildItem -LiteralPath $PSScriptRoot -Filter '*.ps1' -File)) {
        $Tokens = $null
        $ParseErrors = $null
        [Management.Automation.Language.Parser]::ParseFile($File.FullName, [ref]$Tokens, [ref]$ParseErrors) | Out-Null
        Assert (-not $ParseErrors) "Invalid PowerShell syntax: $($File.FullName)"
    }
    $Ini = Join-Path $Temporary 'config.ini'
    [IO.File]::WriteAllText($Ini, "[Other]`r`nValue=keep`r`n[Target]`r`nKey=old`r`nKey=duplicate`r`n")
    Set-ReleaseIniValue $Ini '[Target]' 'Key' 'new'
    Set-ReleaseIniValue $Ini '[New]' 'Enabled' 'True'
    $Text = [IO.File]::ReadAllText($Ini)
    Assert ($Text.Contains('Value=keep') -and $Text.Contains('Enabled=True')) 'INI lost unrelated content'
    Assert (([regex]::Matches($Text, 'Key=')).Count -eq 1 -and $Text.Contains('Key=new')) 'INI key not replaced exactly once'

    $Project = Join-Path $Temporary 'demo project/Demo.uproject'
    $GeneratedDir = Join-Path (Split-Path -Parent $Project) 'Source/Demo/Generated'
    New-Item -ItemType Directory -Path $GeneratedDir -Force | Out-Null
    $Generated = Join-Path $GeneratedDir 'UnLuaNovaStaticBinding_Generated.cpp'
    $Unrelated = Join-Path $GeneratedDir 'HandWritten.cpp'
    [IO.File]::WriteAllText($Unrelated, '// preserve this file')
    $Empty = Backup-ReleaseStaticBindings $Project (Join-Path $Temporary 'empty-backup')
    Assert (-not $Empty.Backup -and $Empty.Source -eq $Generated) 'Missing bindings should need no backup'
    [IO.File]::WriteAllText($Generated, '// not generated')
    $Failed = $false
    try { Backup-ReleaseStaticBindings $Project (Join-Path $Temporary 'rejected-backup') | Out-Null }
    catch { $Failed = $_.Exception.Message -like 'Refusing to archive*' }
    Assert ($Failed -and [IO.File]::ReadAllText($Generated) -eq '// not generated') 'Unrecognized source was modified'
    $OldSource = "// Generated by UnLuaNovaStaticBindingGenerator. Do not edit.`r`n// obsolete thunk format`r`n"
    [IO.File]::WriteAllText($Generated, $OldSource)
    $OldHash = (Get-FileHash -LiteralPath $Generated).Hash
    $Backup = Backup-ReleaseStaticBindings $Project (Join-Path $Temporary 'binding backup')
    Assert (-not (Test-Path -LiteralPath $Generated)) 'Old translation unit still participates in bootstrap compilation'
    Assert ((Get-FileHash -LiteralPath $Backup.Backup).Hash -eq $OldHash) 'Backup changed generated bytes'
    Assert ([IO.File]::ReadAllText($Unrelated) -eq '// preserve this file') 'Bootstrap modified another source'
    Restore-ReleaseStaticBindings $Backup
    Assert ((Get-FileHash -LiteralPath $Generated).Hash -eq $OldHash) 'Failed bootstrap did not recover original bytes'
    Assert (Test-Path -LiteralPath $Backup.Backup) 'Recovery discarded backup evidence'
    $SecondBackup = Backup-ReleaseStaticBindings $Project (Join-Path $Temporary 'second-backup')
    [IO.File]::WriteAllText($Generated, '// newly generated output')
    Restore-ReleaseStaticBindings $SecondBackup
    Assert ([IO.File]::ReadAllText($Generated) -eq '// newly generated output') 'Recovery overwrote newer output'

    # Real child process, no compiler or UE. Verify quoting and nonzero exit propagation.
    $Arguments = @('space path\', 'embedded"quote', '', '-value=two words', 'literal $() and `backticks`')
    $Probe = Join-Path $PSScriptRoot 'fixtures/argv_probe.py'
    $Log = Join-Path $Temporary 'argv.log'
    Invoke-ReleaseProcess -File (Get-Command python).Source -Arguments (@($Probe) + $Arguments) -Log $Log -WorkingDirectory $Temporary
    $Actual = Get-Content $Log -Raw | ConvertFrom-Json
    Assert ($Actual.Count -eq $Arguments.Count) 'Argument count changed'
    for ($Index = 0; $Index -lt $Arguments.Count; $Index++) {
        Assert ($Actual[$Index] -ceq $Arguments[$Index]) "Argument $Index changed"
    }
    $Failed = $false
    try {
        Invoke-ReleaseProcess -File $PowerShellExe -Arguments @('-NoProfile', '-NonInteractive', '-Command', 'exit 7') `
            -Log (Join-Path $Temporary 'failure.log') -WorkingDirectory $Temporary
    } catch { $Failed = $_.Exception.Message -like 'Exit 7:*' }
    Assert $Failed 'Nonzero process exit did not fail the gate'
    $Failed = $false
    try {
        Invoke-ReleaseProcess -File $PowerShellExe -Arguments @('-NoProfile', '-NonInteractive', '-Command', 'Start-Sleep -Seconds 15') `
            -Log (Join-Path $Temporary 'timeout.log') -WorkingDirectory $Temporary -Minutes 0.01
    } catch { $Failed = $_.Exception.Message -like 'Timeout*' }
    Assert $Failed 'Process timeout did not fail the gate'

    # Packaged Server and Game peers have different executable paths.
    $PeerRoot = Join-Path $Temporary 'peers'
    New-Item -ItemType Directory -Path $PeerRoot | Out-Null
    $PeerStarted = [datetime]::UtcNow.AddSeconds(-1)
    $PythonRuntime = (& python -c 'import sys; print(sys.executable)').Trim()
    $PeerProcess = Start-Process -FilePath $PythonRuntime -ArgumentList @('-c', '"import time; time.sleep(30)"') -WindowStyle Hidden -PassThru
    try {
        $PeerPath = (Get-Process -Id $PeerProcess.Id).Path
        @{ exe = $PowerShellExe; peers = @(@{ pid = $PeerProcess.Id; exe = $PowerShellExe }) } |
            ConvertTo-Json -Depth 4 | Set-Content (Join-Path $PeerRoot 'topology.json')
        Stop-ReleasePeers $PeerRoot $PeerStarted
        $PeerProcess.Refresh()
        Assert (-not $PeerProcess.HasExited) 'Cleanup terminated a mismatched executable'
        @{ exe = $PowerShellExe; peers = @(@{ pid = $PeerProcess.Id; exe = $PeerPath }) } |
            ConvertTo-Json -Depth 4 | Set-Content (Join-Path $PeerRoot 'topology.json')
        Stop-ReleasePeers $PeerRoot $PeerStarted
        Assert ($PeerProcess.WaitForExit(5000)) 'Cleanup ignored the per-peer executable'
    } finally {
        if (-not $PeerProcess.HasExited) { $PeerProcess.Kill() }
        $PeerProcess.Dispose()
    }

    $Before = Get-FileHash (Join-Path $RepoRoot 'Config/DefaultUnLuaNova.ini')
    Invoke-ReleaseProcess -File $PowerShellExe -Arguments @('-NoProfile', '-NonInteractive', '-File',
        (Join-Path $Tools 'RunTests.ps1'), '-DryRun') -Log (Join-Path $Temporary 'dry-run.log') -WorkingDirectory $RepoRoot
    Assert ((Get-FileHash $Before.Path).Hash -eq $Before.Hash) 'DryRun modified project config'
    $Failed = $false
    try {
        Invoke-ReleaseProcess -File $PowerShellExe -Arguments @('-NoProfile', '-NonInteractive', '-File',
            (Join-Path $Tools 'RunTests.ps1'), '-DryRun', '-SkipBuild') -Log (Join-Path $Temporary 'partial.log') -WorkingDirectory $RepoRoot
    } catch { $Failed = $true }
    Assert $Failed 'Release accepted reduced coverage'
    $Failed = $false
    $FailedOutput = Join-Path $Temporary 'preflight-report'
    try {
        Invoke-ReleaseProcess -File $PowerShellExe -Arguments @('-NoProfile', '-NonInteractive', '-File',
            (Join-Path $Tools 'RunTests.ps1'), '-EnginePath', (Join-Path $Temporary 'missing-engine'),
            '-OutputDir', $FailedOutput) -Log (Join-Path $Temporary 'preflight.log') -WorkingDirectory $RepoRoot
    } catch { $Failed = $true }
    Assert $Failed 'Missing engine was accepted'
    $Summary = Get-Content (Join-Path $FailedOutput 'release-summary.json') -Raw | ConvertFrom-Json
    Assert ($Summary.complete -and -not $Summary.passed) 'Failed preflight lost the aggregate verdict'
    Assert (@($Summary.stages | Where-Object status -eq 'blocked').Count -eq 33) 'Unexecuted stages disappeared from summary'
    Assert ((Get-FileHash $Before.Path).Hash -eq $Before.Hash) 'Failed preflight modified project config'
    Write-Host 'Release support tests passed.'
} finally {
    $Resolved = [IO.Path]::GetFullPath($Temporary)
    $ExpectedParent = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\') + '\'
    if ($Resolved.StartsWith($ExpectedParent, [StringComparison]::OrdinalIgnoreCase) -and
        [IO.Path]::GetFileName($Resolved).StartsWith('UnLuaNova-release-test-')) {
        Remove-Item -LiteralPath $Resolved -Recurse -Force
    }
}
